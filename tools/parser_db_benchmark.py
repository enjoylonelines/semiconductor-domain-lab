import json
import statistics
import tempfile
import time
from pathlib import Path
from eda_lab.parser import parse_report_streaming
from eda_lab.store import Store


def percentile(values, p):
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(len(ordered) * p / 100))]


def main():
    metric_count = 20000
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "large.synthetic.report"
        with path.open("w", encoding="utf-8") as handle:
            handle.write("SYNTHETIC / NOT GENERATED BY AN EDA TOOL\n")
            handle.write("fixture_format_version=1\nrun_id=large-1\nstage=timing\ncorner=TT_25C\ntool_exit_code=0\nworst_slack=0.12 ns\n")
            for index in range(120000):
                handle.write(f"# synthetic detail line {index:06d} padding for streaming parser benchmark\n")
        parse_started = time.perf_counter()
        parsed = parse_report_streaming(path)
        parse_seconds = time.perf_counter() - parse_started

        store = Store()
        store.create_run("large-1", "design-large", "PCIe", "synthetic-timing")
        rows = [("large-1", "worst_slack", "timing", "TT_25C", 0.12 + (index % 100) / 1000, "ns") for index in range(metric_count)]
        insert_started = time.perf_counter()
        store.save_metric_rows(rows)
        insert_seconds = time.perf_counter() - insert_started
        query_times = []
        for _ in range(30):
            query_started = time.perf_counter()
            summary = store.query_metric_summary("timing", "TT_25C", "worst_slack")
            query_times.append(time.perf_counter() - query_started)
        payload = {
            "synthetic": True,
            "artifact_bytes": path.stat().st_size,
            "metric_rows": metric_count,
            "parse_status": parsed.parse_status,
            "parse_seconds": round(parse_seconds, 6),
            "batch_insert_seconds": round(insert_seconds, 6),
            "query": {
                "count": summary["count"],
                "mean_seconds": round(statistics.mean(query_times), 6),
                "p95_seconds": round(percentile(query_times, 95), 6),
                "max_seconds": round(max(query_times), 6),
            },
        }
        print(json.dumps(payload, sort_keys=True))


if __name__ == "__main__":
    main()
